#!/usr/bin/env node
"use strict";
/**
 * Independent IEEE benchmark replay: JS normal equations, not R or Python.
 * External gasfluxes GPL fixture; never a CH4 mass/emissions certification.
 */
const fs=require("node:fs");
const path=require("node:path");
const crypto=require("node:crypto");

const ROOT=path.resolve(__dirname,"..");
const BASE=path.join(ROOT,"research/ieee-observation-datasets-2026-10-19/independent-benchmarks/gasfluxes-v0.7-2");
const CSV=path.join(BASE,"fluxmeas-first-five.csv");
const MANIFEST=path.join(BASE,"oracle.json");

function reject(code){throw Error("IEEE_GASFLUXES_NODE_BLOCKED:"+code)}
function fixedRead(filepath,cap){
 const st=fs.lstatSync(filepath);
 if(!st.isFile()||st.isSymbolicLink()||st.size>cap) reject("UNSAFE_SOURCE_FILE");
 return fs.readFileSync(filepath);
}
function load(){
 const m=JSON.parse(fixedRead(MANIFEST,20000).toString("utf8"));
 if(m.schema!=="naft-ieee-gasfluxes-linear-oracle-v1"||
    m.dataset.pinned_commit!=="0a50f94bc7c1d6560bb5f32a596c7092d35c079c"||
    m.dataset.full_source_blob_sha!=="ff5e9982b5c24583342ce6e358aae368b6a710ea"||
    m.dataset.source_license!=="GPL-2.0-or-later"||
    m.reference.test_blob_sha!=="410dd826565f137fc5c7abfff16c3d06b935aa51"||
    m.reference.reference_upstream_algorithm_executed_in_naft!==false||
    m.safety.certified_tco2e!==null||
    m.safety.method_applied_to_Gimje!==false)reject("MANIFEST_BOUNDARY");
 return m;
}
function numeric(s){
 if(typeof s!=="string"||s.length>80||!/^[+-]?(?:\d+(?:\.\d*)?|\.\d+)(?:[Ee][+-]?\d+)?$/.test(s)) reject("NUMERIC_TOKEN_INVALID");
 const n=Number(s);
 if(!Number.isFinite(n))reject("NONFINITE_NUMERIC");
 return n;
}
function parseRows(raw,expected){
 if(!Buffer.isBuffer(raw)||raw.length>3000||crypto.createHash("sha256").update(raw).digest("hex")!==expected)reject("ORIGINAL_FIXTURE_HASH");
 const s=raw.toString("utf8");
 if(s.includes("\uFFFD")||!s.endsWith("\r\n"))reject("ORIGINAL_ENCODING");
 const lines=s.split("\r\n");
 if(lines.pop()!==""||lines.length!==21||lines[0]!=="ID;V;A;time;C")reject("EXPECTED_20_ORIGINAL_ROWS");
 const groups=new Map([["ID1",[]],["ID2",[]],["ID3",[]],["ID4",[]],["ID5",[]]]);
 for(const line of lines.slice(1)){
  const v=line.split(";");
  if(v.length!==5||!groups.has(v[0]))reject("UNKNOWN_OR_MALFORMED_ROW");
  const [id,V,A,t,C]=v;
  groups.get(id).push({V:numeric(V),A:numeric(A),t:numeric(t),C:numeric(C)});
 }
 if([...groups.values()].some(x=>x.length!==4))reject("SOURCE_SERIES_COUNT");
 return groups;
}
function solve(groups){
 const results=[];
 for(const [id,pts] of groups){
  if(pts.some(x=>x.V!==pts[0].V||x.A!==pts[0].A)||pts[0].V<=0||pts[0].A<=0)reject("INCONSISTENT_CHAMBER_GEOMETRY");
  if(new Set(pts.map(x=>x.t)).size!==pts.length||pts.some(x=>x.t<0||x.t>1))reject("TIME_DUPLICATE_OR_OUT_OF_SCOPE");
  // Normal equations, independent of the Python centered-covariance
  // implementation. The upstream golden values were generated by R lm().
  const n=pts.length;
  let sx=0,sy=0,sxx=0,sxy=0;
  for(const p of pts){sx+=p.t;sy+=p.C;sxx+=p.t*p.t;sxy+=p.t*p.C}
  const denominator=n*sxx-sx*sx;
  if(!Number.isFinite(denominator)||denominator<=0)reject("ZERO_TIME_SPREAD");
  const slope=(n*sxy-sx*sy)/denominator;
  const intercept=(sy-slope*sx)/n;
  const f0=slope*pts[0].V/pts[0].A;
  if(![slope,intercept,f0].every(Number.isFinite))reject("NONFINITE_FIT");
  results.push({
   id, samples:pts.length, concentration_trend_slope:slope,
   linear_f0_benchmark_value:f0,
   linear_C0_benchmark_intercept:intercept,
   scientific_QC_approved:false
  });
 }
 return results;
}
function replay(raw=fixedRead(CSV,3000),m=load()){
 const measurements=parseRows(raw,m.dataset.fixture_sha256);
 const series=solve(measurements);
 const gold=m.reference.expected_linear_f0_by_series;
 if(!Array.isArray(gold)||gold.length!==5)reject("MISSING_REFERENCE_ORACLE");
 for(let i=0;i<series.length;i++){
  const reference=gold[i],observed=series[i];
  if(reference.id!==observed.id||
     Math.abs(observed.linear_f0_benchmark_value-numeric(reference.f0))>1e-10||
     Math.abs(observed.linear_C0_benchmark_intercept-numeric(reference.C0))>1e-10)
    reject("INDEPENDENT_REFERENCE_DISAGREEMENT");
 }
 return {
  schema:"naft-ieee-independent-gasfluxes-node-v1",
  status:"INDEPENDENT_NODE_REPLAY_MATCHED_PUBLISHED_R_GOLDEN_VALUES",
  selected_source_sha256:crypto.createHash("sha256").update(raw).digest("hex"),
  source_git_commit:m.dataset.pinned_commit,
  upstream_expected_values_source:m.reference.test_path,
  independent_calculation:"NODE_NUMBER_NORMAL_EQUATIONS",
  upstream_R_code_executed:false,
  comparison_tolerance:"1e-10 fixture units",
  series,
  measurement_unit_certified:false,
  Gimje_field_validation:false,
  official_mrv_eligibility:false,
  certified_tco2e:null,
 };
}
if(require.main===module){
 const index=process.argv.indexOf("--output");
 if(index>=0&&(!process.argv[index+1]||index+2!==process.argv.length))reject("OUTPUT_ARGUMENT");
 if(index<0&&process.argv.length!==2)reject("UNEXPECTED_ARGUMENT");
 const result=JSON.stringify(replay(),null,2)+"\n";
 if(index>=0){fs.mkdirSync(path.dirname(process.argv[index+1]),{recursive:true});fs.writeFileSync(process.argv[index+1],result)}
 else process.stdout.write(result);
}
module.exports={load,parseRows,solve,replay,reject};
